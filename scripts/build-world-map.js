// Turns Natural Earth land outlines (TopoJSON from the `world-atlas` npm package) into one
// pre-projected SVG path, written to public/world-map.js. Run only when updating the map:
//
//   npm pack world-atlas@2 && tar xzf world-atlas-*.tgz
//   node scripts/build-world-map.js package/land-110m.json
//
// Map data: Natural Earth (public domain), via world-atlas (ISC). See THIRD-PARTY-NOTICES.md.
'use strict';
const fs = require('node:fs');
const path = require('node:path');
const { project, WIDTH, HEIGHT } = require('../public/map-projection');

const input = process.argv[2];
if (!input) {
  console.error('Usage: node scripts/build-world-map.js <path/to/land-110m.json>');
  process.exit(1);
}
const topo = JSON.parse(fs.readFileSync(input, 'utf8'));

// TopoJSON arcs are delta-encoded integers; undo the quantization to get [lon, lat].
const { scale: [kx, ky], translate: [dx, dy] } = topo.transform;
const arcs = topo.arcs.map(arc => {
  let x = 0, y = 0;
  return arc.map(([ax, ay]) => [(x += ax) * kx + dx, (y += ay) * ky + dy]);
});
// An arc index < 0 means "arc ~i, reversed" (TopoJSON spec).
const arcPoints = i => (i < 0 ? arcs[~i].slice().reverse() : arcs[i]);
const ring = idx => idx.flatMap((i, n) => (n ? arcPoints(i).slice(1) : arcPoints(i)));

const polygons = [];
for (const g of topo.objects.land.geometries) {
  if (g.type === 'Polygon') polygons.push(g.arcs);
  if (g.type === 'MultiPolygon') polygons.push(...g.arcs);
}

// Land crossing the 180° meridian (Russia's far east, Fiji) jumps from one map edge to the
// other. Each jump flips us to the other side of the map, so split the ring into the runs on
// each side of the crossings and close each side separately.
function splitAtAntimeridian(pts) {
  const sides = [[], []];
  let side = 0;
  pts.forEach((p, i) => {
    if (i && Math.abs(p[0] - pts[i - 1][0]) > WIDTH / 2) side ^= 1;
    sides[side].push(p);
  });
  return sides.filter(s => s.length > 2);
}

// Drop points that land on the same tenth of a unit as the previous one.
function toPath(pts) {
  let last = '', seg = '';
  for (const [x, y] of pts) {
    const p = `${x.toFixed(1)} ${y.toFixed(1)}`;
    if (p === last) continue;
    seg += `${seg ? 'L' : 'M'}${p}`;
    last = p;
    points++;
  }
  return seg + 'Z';
}

let d = '';
let points = 0;
for (const poly of polygons) {
  for (const r of poly) {
    const pts = ring(r).map(([lon, lat]) => project(lon, lat));
    if (pts.every(([, y]) => y > HEIGHT) || pts.every(([, y]) => y < 0)) continue; // fully cropped (Antarctica)

    for (const part of splitAtAntimeridian(pts)) d += toPath(part);
  }
}

const out = `// SPDX-License-Identifier: MIT
// Generated by scripts/build-world-map.js — do not edit by hand.
// Land outlines: Natural Earth 1:110m (public domain), via world-atlas (ISC).
window.WORLD_MAP = { width: ${WIDTH}, height: ${HEIGHT}, land: ${JSON.stringify(d)} };
`;
const dest = path.join(__dirname, '..', 'public', 'world-map.js');
fs.writeFileSync(dest, out);
console.log(`Wrote ${dest}: ${polygons.length} polygons, ${points} points, ${(out.length / 1024).toFixed(1)} KB (${WIDTH}×${HEIGHT})`);
